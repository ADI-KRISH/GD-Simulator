<#
.SYNOPSIS
  Starts GD on a throwaway demo database seeded with synthetic traces.

.DESCRIPTION
  Opens http://localhost:5214/observability. Sign in as demo.host@example.com /
  demo-pass-1234. Every number on that page is generated by scripts/seed_demo_traces.py.
  Delete gd_demo.db to start over. Stop the two windows it opens to stop the demo.
#>

$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
$env:DATABASE_URL = sqlite+aiosqlite:///./gd_demo.db
$env:APP_ENV = local
$env:REDIS_URL = disabled
$env:OBJECT_STORE = filesystem
$env:PYTHONPATH = $root
$py = Join-Path $root .venv\Scripts\python.exe

if (-not (Test-Path gd_demo.db)) {
    & (Join-Path $root .venv\Scripts\alembic.exe) upgrade head
    & $py scripts\seed_demo_traces.py
}

Start-Process powershell -ArgumentList -NoExit, -Command, "cd $root; `$env:DATABASE_URL=sqlite+aiosqlite:///./gd_demo.db; `$env:APP_ENV=local; `$env:REDIS_URL=disabled; `$env:OBJECT_STORE=filesystem; & $py -m uvicorn services.main:app --port 8114"
Start-Process powershell -ArgumentList -NoExit, -Command, "cd $root\frontend; npx next dev -p 5214"

Start-Sleep -Seconds 10
$body = @{ email = demo.host@example.com; full_name = Demo Host; password = demo-pass-1234; role = host } | ConvertTo-Json
try { Invoke-RestMethod -Method Post -Uri http://localhost:8114/api/v1/auth/register -ContentType application/json -Body $body | Out-Null } catch { }
Write-Host Open http://localhost:5214/login, sign in as demo.host@example.com / demo-pass-1234, then choose Observability.
